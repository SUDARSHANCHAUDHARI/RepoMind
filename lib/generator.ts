import OpenAI from "openai";
import { RepoAnalysis, GeneratedProject } from "@/types";

export async function generateStarterRepo(analysis: RepoAnalysis, apiKey: string): Promise<GeneratedProject> {
  const client = new OpenAI({ apiKey });
  const prompt = `You are a senior full-stack engineer who writes clean, production-ready boilerplate.

Based on this repo analysis, generate a real working starter project.

ANALYSIS:
Name: ${analysis.meta.name}
Tech Stack: ${analysis.architect.techStack.join(", ")}
Core Features: ${analysis.features.coreFeatures.join(", ")}
Architecture: ${analysis.architect.architecture}
Tech Recommendations: ${analysis.builder.techRecommendations.join(", ")}

REQUIREMENTS:
- Generate 6-10 real files
- Use Next.js 14 App Router + TypeScript + Tailwind
- Include package.json with correct dependencies
- Include at least one API route
- Include a working home page
- Include a proper README.md with setup steps
- All file content must be real, working code — no placeholders
- Keep each file focused and clean

Return ONLY valid JSON in this exact shape:
{
  "stack": "Next.js 14 + TypeScript + Tailwind",
  "instructions": "1. npm install\\n2. npm run dev\\n3. Open http://localhost:3000",
  "files": [
    {
      "path": "package.json",
      "content": "{ ... }"
    },
    {
      "path": "app/page.tsx",
      "content": "..."
    }
  ]
}`;

  try {
    const res = await client.chat.completions.create({
      model: "gpt-4.1",
      temperature: 0.2,
      max_tokens: 4096,
      messages: [{ role: "user", content: prompt }],
      response_format: { type: "json_object" },
    });

    const text = res.choices[0]?.message?.content;
    if (!text) throw new Error("Empty response from AI");
    return JSON.parse(text) as GeneratedProject;
  } catch (err) {
    console.error("Generator error:", err);
    // Return a minimal fallback project
    return {
      stack: analysis.builder.techRecommendations.join(", ") || "Next.js + Tailwind",
      instructions: "1. npm install\n2. npm run dev\n3. Open http://localhost:3000",
      files: [
        {
          path: "package.json",
          content: JSON.stringify({
            name: analysis.meta.name.toLowerCase().replace(/\s/g, "-") + "-clone",
            version: "0.1.0",
            scripts: { dev: "next dev", build: "next build" },
            dependencies: { next: "14.2.3", react: "^18", "react-dom": "^18", typescript: "^5", tailwindcss: "^3" },
          }, null, 2),
        },
        {
          path: "app/page.tsx",
          content: `export default function Home() {\n  return (\n    <main className="p-8">\n      <h1 className="text-3xl font-bold">${analysis.meta.name} Clone</h1>\n      <p className="mt-2 text-gray-600">${analysis.meta.description || "Built with RepoMind AI"}</p>\n    </main>\n  );\n}\n`,
        },
        {
          path: "README.md",
          content: `# ${analysis.meta.name} Clone\n\nGenerated by RepoMind AI.\n\n## Stack\n${analysis.builder.techRecommendations.join(", ")}\n\n## Setup\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n`,
        },
      ],
    };
  }
}
